def _balanced(
    options: tuple[str, str, str, str], answer: str, number: int
) -> tuple[list[str], str]:
    """把正确项换到目标位置，让 A/B/C/D 各占四分之一。

    ★ **不做这一步，全集会严重偏向 B**（手写选择题的通病：正确项习惯性写在第二位）。
    一个「永远答 B」的模型能拿到 57%~77%，回归测试就此失灵 —— 微调后掉多少都可能
    被这层地板盖住。这里用**交换**而不是打乱：选项集合不变，只换位置，可复现。
    """
    target = "ABCD"[(number - 1) % 4]
    src, dst = "ABCD".index(answer), "ABCD".index(target)
    items = list(options)
    items[src], items[dst] = items[dst], items[src]
    return items, target


def _mcq(
    number: int,
    layer: str,
    question: str,
    options: tuple[str, str, str, str],
    answer: str,
    why: str,
) -> dict[str, Any]:
    options_list, answer = _balanced(options, answer, number)
    options = (options_list[0], options_list[1], options_list[2], options_list[3])
    return {
        "item_id": f"OOD-{PREFIX[layer]}-{number:03d}",
        "layer": layer,
        "judge": "multiple_choice",
        "prompt": question
        + "\n"
        + "\n".join(f"{k}. {v}" for k, v in zip("ABCD", options, strict=True)),
        "follow_ups": [],
        "options": list(options),
        "answer": answer,
        "accepted": [],
        "pattern": None,
        "tolerance": None,
        "forbidden": [],
        "rationale": why,
    }


